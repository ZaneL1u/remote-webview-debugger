// The words `init` and `doctor` print, in the same 11 languages as the
// gateway, the SDK and the console. The language comes from RWD_LANG, then the
// terminal's locale (LC_ALL, LC_MESSAGES, LANG, LANGUAGE), then, on macOS, the
// system language. The stdio server itself prints nothing for people to read.
import { execFileSync } from 'node:child_process'

export const LANGS = ['en', 'zh', 'zh-TW', 'ja', 'ko', 'es', 'fr', 'de', 'pt', 'ru', 'ar'] as const
export type Lang = (typeof LANGS)[number]

/** Maps a locale (zh_CN.UTF-8, zh-Hant-TW, pt_BR, en) to a supported language, or undefined. */
export function langOf(locale: string | undefined): Lang | undefined {
  if (!locale) return undefined
  const l = locale.trim().replace(/[.@].*$/, '').replace(/_/g, '-').toLowerCase()
  if (!l || l === 'c' || l === 'posix') return undefined
  if (l.startsWith('zh')) return /^zh-(tw|hk|mo|hant)/.test(l) ? 'zh-TW' : 'zh'
  const base = l.split('-')[0]
  return (LANGS as readonly string[]).includes(base!) ? (base as Lang) : base ? 'en' : undefined
}

/** The language from the environment only (what tests and --lang-less runs on Linux see). */
export function langFromEnv(env: Record<string, string | undefined>): Lang | undefined {
  for (const v of [env.RWD_LANG, env.LC_ALL, env.LC_MESSAGES, env.LANG, env.LANGUAGE?.split(':')[0]]) {
    const l = langOf(v)
    if (l) return l
  }
  return undefined
}

/** The person's language: the environment, then the system setting (macOS, Windows), then English. */
export function detectLang(env: Record<string, string | undefined>, platform: NodeJS.Platform = process.platform): Lang {
  const fromEnv = langFromEnv(env)
  if (fromEnv) return fromEnv
  try {
    if (platform === 'darwin') {
      const l = langOf(execFileSync('defaults', ['read', '-g', 'AppleLocale'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], timeout: 2000 }))
      if (l) return l
    }
  } catch {}
  return langOf(Intl.DateTimeFormat().resolvedOptions().locale) ?? 'en'
}

